create table if not exists public.quiz_questions (
  id bigint generated by default as identity primary key,
  question_order integer not null unique,
  question_text text not null,
  option_a text not null,
  option_b text not null,
  option_c text not null,
  option_d text not null,
  correct_option smallint not null check (correct_option between 1 and 4),
  explanation text not null default '',
  active boolean not null default true
);

create table if not exists public.quiz_results (
  id bigint generated by default as identity primary key,
  student_name text not null check (char_length(trim(student_name)) between 1 and 100),
  student_class text not null check (char_length(trim(student_class)) between 1 and 30),
  score integer not null check (score between 0 and 100),
  correct_count integer not null check (correct_count between 0 and 20),
  total_questions integer not null default 20 check (total_questions = 20),
  submitted_at timestamptz not null default now()
);

alter table public.quiz_questions enable row level security;
alter table public.quiz_results enable row level security;
revoke all on public.quiz_questions from anon, authenticated;
revoke all on public.quiz_results from anon, authenticated;

create or replace view public.quiz_questions_public as
select id, question_order, question_text, option_a, option_b, option_c, option_d
from public.quiz_questions where active = true;
grant select on public.quiz_questions_public to anon, authenticated;

create or replace function public.submit_ifelse_quiz(
 p_student_name text, p_student_class text, p_answers jsonb
) returns table(result_id bigint, score integer, correct_count integer, total_questions integer, submitted_at timestamptz)
language plpgsql security definer set search_path = public, pg_temp
as $$
declare v_total integer; v_answered integer; v_correct integer; v_score integer; v_result_id bigint; v_submitted_at timestamptz;
begin
 if p_student_name is null or char_length(trim(p_student_name)) not between 1 and 100 then raise exception 'Nama siswa wajib diisi, maksimal 100 karakter.'; end if;
 if p_student_class is null or char_length(trim(p_student_class)) not between 1 and 30 then raise exception 'Kelas wajib diisi, maksimal 30 karakter.'; end if;
 if jsonb_typeof(p_answers) <> 'array' then raise exception 'Format jawaban tidak valid.'; end if;
 select count(*) into v_total from public.quiz_questions where active = true;
 if v_total <> 20 then raise exception 'Kuis harus memiliki tepat 20 soal aktif; ditemukan %.',v_total; end if;
 if jsonb_array_length(p_answers) <> v_total then raise exception 'Semua 20 soal wajib dijawab.'; end if;
 select count(*) into v_answered from jsonb_array_elements(p_answers) as items(item)
 where (item->>'question_id') ~ '^[0-9]+$' and (item->>'selected_option') ~ '^[1-4]$';
 if v_answered <> v_total then raise exception 'Ada jawaban yang tidak valid.'; end if;
 if (select count(distinct (item->>'question_id')::bigint) from jsonb_array_elements(p_answers) as items(item)) <> v_total then raise exception 'Ada ID soal ganda.'; end if;
 if exists (select 1 from jsonb_array_elements(p_answers) as items(item) left join public.quiz_questions q on q.id=(item->>'question_id')::bigint and q.active=true where q.id is null) then raise exception 'Ada soal yang tidak valid atau tidak aktif.'; end if;
 select count(*) into v_correct from jsonb_array_elements(p_answers) as items(item) join public.quiz_questions q on q.id=(item->>'question_id')::bigint
 where q.active=true and q.correct_option=(item->>'selected_option')::smallint;
 v_score := round((v_correct::numeric / v_total)*100)::integer;
 insert into public.quiz_results(student_name,student_class,score,correct_count,total_questions)
 values(trim(p_student_name),trim(p_student_class),v_score,v_correct,v_total)
 returning id, quiz_results.submitted_at into v_result_id,v_submitted_at;
 return query select v_result_id,v_score,v_correct,v_total,v_submitted_at;
end; $$;
revoke all on function public.submit_ifelse_quiz(text,text,jsonb) from public;
grant execute on function public.submit_ifelse_quiz(text,text,jsonb) to anon, authenticated;

